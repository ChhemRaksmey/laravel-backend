SELECT
    r.recid,
    elem.value AS risk_country
FROM aml_risk_countries r
LEFT JOIN LATERAL json_array_elements_text(
    CASE
        WHEN json_typeof(r.json_data->'c1') = 'array' THEN r.json_data->'c1'
        ELSE '[]'::json
    END
) WITH ORDINALITY AS elem(value, ordinality) ON TRUE;
